
import sharp from 'sharp';
import fs from 'fs';
import path from 'path';
import { fileURLToPath } from 'url';

const __filename = fileURLToPath(import.meta.url);
const __dirname = path.dirname(__filename);
const projectRoot = path.join(__dirname, '..');
const publicDir = path.join(projectRoot, 'public');

// Configuration
const THEME_COLOR = '#ff2465'; // New Brand Color
const BG_COLOR = '#0A0A0A';   // New Background Color

// Source Files
const sources = {
    icon512: path.join(publicDir, 'AppImages/android/android-launchericon-512-512.png'),
    icon192: path.join(publicDir, 'AppImages/android/android-launchericon-192-192.png'),
    appleIcon: path.join(publicDir, 'favicon_io/apple-touch-icon.png'),
    favicon: path.join(publicDir, 'favicon_io/favicon.ico'),
    // Also grab a source for favicon generation if needed, usually 512 or 192
    faviconSource: path.join(publicDir, 'AppImages/android/android-launchericon-512-512.png')
};

// Destinations
const destinations = {
    icon512: path.join(publicDir, 'icon-512x512.png'),
    icon192: path.join(publicDir, 'icon-192x192.png'),
    appleIcon: path.join(publicDir, 'apple-touch-icon.png'),
    favicon: path.join(publicDir, 'favicon.ico')
};

async function processIcon(inputPath, outputPath, size) {
    console.info(`Processing ${inputPath} -> ${outputPath}`);

    try {
        // Load image
        let image = sharp(inputPath);
        const metadata = await image.metadata();

        // Strategy: 
        // 1. Create a background layer
        // 2. Load the input image. 
        //    If it has transparency, good.
        //    If we want to "override colors":
        //    - We can try to turn non-transparent pixels to THEME_COLOR.
        //    - Or simply composite it if it's already white/correct shape.

        // For this task, "override or re-write all colors".
        // Let's assume the shape is important. 
        // We will maintain the alpha channel but fill the RGB channels with THEME_COLOR?
        // Or is it a logo on a background? 
        // Android launcher icons usually have a background.

        // Better Approach for "Re-write all colors":
        // 1. Extract the alpha channel (mask).
        // 2. Create a new image of size X with BG_COLOR.
        // 3. Create a layer of THEME_COLOR masked by the original alpha (or original luminance if no alpha).

        // However, if the source icon is already a square with background, we need to remove the background?
        // Let's assume the source PNGs provided might have their own background or be transparent.
        // Let's check metadata first.

        console.info(`Format: ${metadata.format}, Channels: ${metadata.channels}, HasAlpha: ${metadata.hasAlpha}`);

        // If it's a solid square, it's hard to separate logo from background programmatically without heuristics.
        // Let's assume standard android assets often have transparency or distinct foreground.

        // RECOLORING STRATEGY:
        // 1. Convert to grayscale.
        // 2. Threshold to get a mask? 
        // Unsafe.

        // Conservative STRATEGY:
        // 1. Create a canvas of BG_COLOR.
        // 2. Composite the verified transparent icon on top.
        // BUT if the user wants to CHANGE colors...

        // Let's try to Tint the image.
        // "tint" operation in sharp tints the non-transparent pixels.

        // Let's try to just resize and start with that, but user said "override colors".

        // Let's create a NEW background.
        const background = await sharp({
            create: {
                width: size,
                height: size,
                channels: 4,
                background: BG_COLOR
            }
        }).png().toBuffer();

        // Process the Foreground
        // We want the foreground to be THEME_COLOR (#ff2465).
        // We can take the input, treating it as a mask if possible.
        // If the input is fully opaque (common for generated android icons), we can't easily isolate the logo.
        // BUT `AppImages/android/android-launchericon-512-512.png` suggests it *might* be the asset generated by a tool.
        // If it is opaque, we just copy it? No, user said "override colors".

        // Let's attempt to Tint it.
        // If it has alpha, tinting works well.
        // If it is opaque, tinting makes a solid block.

        // Let's assume for a moment the "android-launchericon" is transparent or we are screwed.
        // If it's not transparent, we might need to use the `icons.json` checks to find a transparent one?
        // The icons.json listed "windows11/SmallTile.scale-100.png" etc.
        // Usually, the `AppImages` folder from some generators contains a `Master` or `source`?
        // No, I only saw the android/ios folders.

        // Let's blindly try to Composite over the new background.
        // If the input has a background, it will cover ours.
        // If we really must force color:
        // We can use `.recomb()` or modulations if we knew the specific colors.

        // Decision: 
        // Since I cannot visually see the image, I will assume standard transparent PNG logo.
        // I will:
        // 1. Create base with BG_COLOR.
        // 2. Take input, resize to fit (maybe with some padding if it's full bleed?).
        // 3. Tint the input to THEME_COLOR.
        // 4. Composite.

        // Wait, if I tint the WHOLE input to valid THEME_COLOR, and it was a white logo, it becomes PINK logo.
        // That sounds correct for "override colors".

        const resizedInput = image
            .resize(size, size, { fit: 'contain', background: { r: 0, g: 0, b: 0, alpha: 0 } });

        // Tinting:
        // Sharp's `tint` sets the r,g,b of non-alpha pixels.
        // We'll apply this.

        const tintedInput = await resizedInput
            .tint(THEME_COLOR)
            .toBuffer();

        // Final Composite
        await sharp(background)
            .composite([{ input: tintedInput }])
            .toFile(outputPath);

        console.info(`Success: ${outputPath}`);

    } catch (error) {
        console.error(`Error processing ${inputPath}:`, error);
    }
}

async function copyFile(src, dest) {
    console.info(`Copying ${src} -> ${dest}`);
    try {
        fs.copyFileSync(src, dest);
    } catch (e) {
        console.error(`Failed to copy ${src}:`, e);
    }
}

async function main() {
    console.info('Starting PWA Asset Migration...');

    // Process Icons
    if (fs.existsSync(sources.icon512)) {
        await processIcon(sources.icon512, destinations.icon512, 512);
    } else {
        console.warn(`Source not found: ${sources.icon512}`);
    }

    if (fs.existsSync(sources.icon192)) {
        await processIcon(sources.icon192, destinations.icon192, 192);
    } else {
        console.warn(`Source not found: ${sources.icon192}`);
        // Fallback to resizing 512 if available
        if (fs.existsSync(sources.icon512)) {
            console.info('Falling back to generating 192 from 512 source...');
            await processIcon(sources.icon512, destinations.icon192, 192);
        }
    }

    // Process Apple Touch Icon
    // Apple icons usually don't have transparency (iOS adds black/white automatically if you provide alpha).
    // Apple HIG says: "Avoid transparency". "Rectangular".
    // But since we want to unify, let's make it our Theme color background with Logo.
    // So same process as above, but size might differ. Standard is 180x180 usually, project uses 192 or 512 in manifest?
    // Project config says: { rel: 'apple-touch-icon', href: '/apple-touch-icon.png' }
    // Usually 180x180 is good for apple-touch-icon.
    // Let's use 180x180 but save as apple-touch-icon.png
    if (fs.existsSync(sources.appleIcon)) {
        await processIcon(sources.appleIcon, destinations.appleIcon, 180);
    } else if (fs.existsSync(sources.icon512)) {
        await processIcon(sources.icon512, destinations.appleIcon, 180);
    }

    // Process Favicon
    // If we have a .ico, just move it.
    if (fs.existsSync(sources.favicon)) {
        copyFile(sources.favicon, destinations.favicon);
    } else {
        console.warn('No favicon.ico found to copy.');
    }

    console.info('Asset generation complete.');
}

main();
